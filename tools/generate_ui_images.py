import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
IMG_DIR = os.path.join(ROOT, "docs", "images", "andromeda")

def process_screen_bmps():
    # If BMPs were generated by render_screens.c, process them
    screens = [
        ("screen_nebula_drift.bmp", os.path.join(IMG_DIR, "andromeda_screen_nebula_drift.png"), "BANK I: EVENT HORIZON - NEBULA DRIFT"),
        ("screen_chronos_chop.bmp", os.path.join(IMG_DIR, "andromeda_screen_chronos_chop.png"), "BANK II: QUANTUM STUTTER - CHRONOS CHOP"),
        ("screen_orbital_arp.bmp", os.path.join(IMG_DIR, "andromeda_screen_orbital_arp.png"), "BANK III: COSMIC ARP - ORBITAL ARPEGGIO"),
        ("screen_wormhole_sos.bmp", os.path.join(IMG_DIR, "andromeda_screen_wormhole_sos.png"), "BANK IV: RELATIVITY LOOP - WORMHOLE OVERDUB")
    ]
    for bmp_file, png_file, title in screens:
        if os.path.exists(bmp_file):
            im = Image.open(bmp_file)
            scale = 3
            im_scaled = im.resize((240 * scale, 240 * scale), Image.NEAREST)
            card = Image.new("RGBA", (240 * scale + 80, 240 * scale + 130), (12, 14, 20, 255))
            draw = ImageDraw.Draw(card)
            draw.rounded_rectangle([15, 15, card.width - 15, card.height - 15], radius=16, fill=(20, 24, 32, 255), outline=(60, 70, 90, 255), width=2)
            card.paste(im_scaled, (40, 40))
            draw.text((50, 40 + 240 * scale + 15), title, fill=(160, 190, 240, 255))
            card.save(png_file, "PNG")
            os.remove(bmp_file)

def generate_authentic_mvave_hardware_diagram(output_path=None):
    if output_path is None:
        output_path = os.path.join(IMG_DIR, "andromeda_pedal_hardware_ui.png")
    width, height = 1500, 1100
    im = Image.new("RGBA", (width, height), (10, 12, 18, 255))
    draw = ImageDraw.Draw(im)

    # Global Title
    draw.text((60, 35), "ANDROMEDA // M-VAVE POCKET AMP HARDWARE UI SPECIFICATION", fill=(255, 255, 255, 255))
    draw.text((60, 65), "Authentic 5-Button + Dual-Knob Form Factor • Zhuhai Jieli AC791N @ 360 MHz • Space & Cosmos Granular DSP", fill=(120, 160, 210, 255))

    # --- POCKET AMP PEDAL CHASSIS ---
    # Compact pocket multi-effects enclosure: 120mm x 70mm x 25mm proportion
    pedal_x, pedal_y, pedal_w, pedal_h = 470, 120, 560, 900
    
    # Outer drop shadow
    draw.rounded_rectangle([pedal_x + 10, pedal_y + 14, pedal_x + pedal_w + 10, pedal_y + pedal_h + 14], radius=44, fill=(5, 6, 8, 200))
    # Matte space-gray anodized aluminum housing
    draw.rounded_rectangle([pedal_x, pedal_y, pedal_x + pedal_w, pedal_y + pedal_h], radius=44, fill=(26, 30, 40, 255), outline=(70, 85, 115, 255), width=3)
    # Inner beveled faceplate
    draw.rounded_rectangle([pedal_x + 16, pedal_y + 16, pedal_x + pedal_w - 16, pedal_y + pedal_h - 16], radius=32, fill=(18, 21, 29, 255), outline=(40, 50, 70, 255), width=2)

    # Laser Engraved Header
    draw.text((pedal_x + 175, pedal_y + 35), "A N D R O M E D A", fill=(230, 242, 255, 255))
    draw.text((pedal_x + 185, pedal_y + 55), "M-VAVE POCKET AMP • ANDROMEDA", fill=(100, 135, 180, 255))

    # --- TOP ROTARY KNOB POD (MASTER & PARA) ---
    # 1. Left Rotary Knob: MASTER Volume Potentiometer
    pot_cx, pot_cy, pot_r = pedal_x + 130, pedal_y + 155, 52
    draw.ellipse([pot_cx - pot_r - 4, pot_cy - pot_r - 4, pot_cx + pot_r + 4, pot_cy + pot_r + 4], fill=(12, 14, 20, 255), outline=(60, 75, 100, 255), width=2)
    draw.ellipse([pot_cx - pot_r, pot_cy - pot_r, pot_cx + pot_r, pot_cy + pot_r], fill=(36, 42, 56, 255), outline=(130, 150, 190, 255), width=2)
    # Dial indicator marker at 2 o'clock
    draw.line([pot_cx, pot_cy, pot_cx + 28, pot_cy - 20], fill=(255, 255, 255, 255), width=4)
    draw.ellipse([pot_cx + 26, pot_cy - 22, pot_cx + 30, pot_cy - 18], fill=(255, 255, 255, 255))
    draw.text((pot_cx - 30, pot_cy + pot_r + 10), "MASTER", fill=(210, 230, 255, 255))

    # 2. Right Rotary Knob: PARA Optical Encoder + Center Push Button
    enc_cx, enc_cy, enc_r = pedal_x + pedal_w - 130, pedal_y + 155, 52
    draw.ellipse([enc_cx - enc_r - 4, enc_cy - enc_r - 4, enc_cx + enc_r + 4, enc_cy + enc_r + 4], fill=(12, 14, 20, 255), outline=(246, 196, 66, 255), width=2)
    draw.ellipse([enc_cx - enc_r, enc_cy - enc_r, enc_cx + enc_r, enc_cy + enc_r], fill=(36, 42, 56, 255), outline=(246, 196, 66, 255), width=2)
    # Encoder knurl notches
    draw.line([enc_cx, enc_cy - enc_r + 2, enc_cx, enc_cy - enc_r + 10], fill=(246, 196, 66, 255), width=3)
    draw.line([enc_cx + enc_r - 10, enc_cy, enc_cx + enc_r - 2, enc_cy], fill=(246, 196, 66, 255), width=3)
    draw.line([enc_cx, enc_cy + enc_r - 10, enc_cx, enc_cy + enc_r - 2], fill=(246, 196, 66, 255), width=3)
    draw.line([enc_cx - enc_r + 2, enc_cy, enc_cx - enc_r + 10, enc_cy], fill=(246, 196, 66, 255), width=3)
    # Center push click button inside PARA knob
    btn_r = 22
    draw.ellipse([enc_cx - btn_r, enc_cy - btn_r, enc_cx + btn_r, enc_cy + btn_r], fill=(22, 26, 36, 255), outline=(246, 196, 66, 255), width=2)
    draw.text((enc_cx - 16, enc_cy - 7), "PUSH", fill=(246, 196, 66, 255))
    draw.text((enc_cx - 20, enc_cy + enc_r + 10), "PARA", fill=(246, 196, 66, 255))

    # --- CENTER 1.54" 240x240 COLOR IPS LCD DISPLAY ---
    scr_w, scr_h = 240, 240
    scr_x = pedal_x + (pedal_w - scr_w) // 2
    scr_y = pedal_y + 280
    
    # Outer display bezel & recessed frame
    draw.rectangle([scr_x - 10, scr_y - 10, scr_x + scr_w + 9, scr_y + scr_h + 9], fill=(6, 8, 12, 255), outline=(50, 65, 90, 255), width=2)
    draw.rectangle([scr_x - 2, scr_y - 2, scr_x + scr_w + 1, scr_y + scr_h + 1], fill=(0, 0, 0, 255))
    
    # Embed active screen preview
    if os.path.exists("andromeda_screen_nebula_drift.png"):
        prev = Image.open("andromeda_screen_nebula_drift.png")
        prev_crop = prev.crop((40, 40, 760, 760)).resize((240, 240), Image.BILINEAR)
        im.paste(prev_crop, (scr_x, scr_y))
    else:
        draw.rectangle([scr_x, scr_y, scr_x + scr_w - 1, scr_y + scr_h - 1], fill=(0, 0, 0, 255))

    # --- BOTTOM 5 ILLUMINATED TACTILE BUTTONS STRIP ---
    # In M-VAVE Pocket AMP, the bottom bar houses 5 strictly round circular tactile buttons:
    # [ HOME ]   [ VOL - ]   [ VOL + ]   [ < ]   [ > ]
    strip_y = pedal_y + 590
    strip_h = 100
    draw.rounded_rectangle([pedal_x + 30, strip_y, pedal_x + pedal_w - 30, strip_y + strip_h], radius=24, fill=(14, 17, 24, 255), outline=(45, 55, 75, 255), width=2)

    buttons = [
        ("HOME", 0, "COSMOS / FREEZE", (0, 230, 255, 255)),
        ("VOL-", 1, "PRESET -", (255, 255, 255, 255)),
        ("VOL+", 2, "PRESET +", (255, 255, 255, 255)),
        ("<",    3, "REVERSE BURST", (255, 80, 180, 255)),
        (">",    4, "SOS LOOPER", (255, 180, 50, 255))
    ]

    btn_spacing = 92
    start_btn_x = pedal_x + 85
    for label, idx, desc, col in buttons:
        bx = start_btn_x + idx * btn_spacing
        by = strip_y + 40
        br = 24
        
        # Outer illuminated LED halo ring
        draw.ellipse([bx - br - 3, by - br - 3, bx + br + 3, by + br + 3], fill=(0, 0, 0, 255), outline=col, width=2)
        # Inner round tactile button
        draw.ellipse([bx - br, by - br, bx + br, by + br], fill=(32, 38, 52, 255), outline=(90, 110, 140, 255), width=2)
        
        # Center button label
        lx = bx - 14 if len(label) > 1 else bx - 5
        draw.text((lx, by - 7), label, fill=col)
        
        # Below-button function annotation
        draw.text((bx - 26, strip_y + strip_h + 10), desc, fill=(110, 140, 180, 255))

    # Bottom I/O Ports Indicator
    draw.rounded_rectangle([pedal_x + 80, pedal_y + 790, pedal_x + pedal_w - 80, pedal_y + 850], radius=16, fill=(12, 14, 20, 255), outline=(40, 50, 70, 255), width=1)
    draw.text((pedal_x + 100, pedal_y + 802), "1/4\" INSTRUMENT INPUT  |  1/8\" STEREO OUT  |  USB-C AUDIO", fill=(140, 175, 220, 255))
    draw.text((pedal_x + 125, pedal_y + 824), "BLE 5.0 WIRELESS MIDI (M-VAVE CHOCOLATE EXPANSION)", fill=(0, 210, 235, 255))

    # --- LEFT CALLOUT CARD: INTELLIGENT 5-BUTTON WORKFLOW ---
    draw.rounded_rectangle([40, 140, 420, 780], radius=20, fill=(18, 22, 32, 255), outline=(55, 70, 95, 255), width=2)
    draw.text((60, 165), "INTELLIGENT 5-BUTTON SYSTEM", fill=(246, 196, 66, 255))
    
    items = [
        ("[ HOME ]", "Tap: Toggle Radar HUD / 8-Slot Chain\nDouble-Tap: Tap Tempo modulation\nHold 1.5s: LATCH BUFFER FREEZE (Pad Drone)"),
        ("[ VOL - ]", "Tap: Decrement Preset (P01..P12)\nHold: Rapid Preset Bank Step\nIn Looper: Decrease SOS Decay"),
        ("[ VOL + ]", "Tap: Increment Preset (P01..P12)\nHold: Rapid Preset Bank Step\nIn Looper: Increase SOS Decay"),
        ("[ < ]", "Tap: Instant REVERSE Grain Burst\nHold: Scrub Buffer Pointer Backward\nCreates swelling tape-reverse blooms"),
        ("[ > ]", "Tap: SOS PHRASE LOOPER State Cycle:\nIDLE -> REC -> PLAY -> OVERDUB\nDouble-Tap: Stop | Hold 1.2s: Clear Loop")
    ]
    
    cy = 205
    for title, desc in items:
        draw.text((60, cy), title, fill=(0, 230, 255, 255))
        cy += 24
        for line in desc.split("\n"):
            draw.text((60, cy), "  " + line, fill=(190, 210, 235, 255))
            cy += 20
        cy += 14

    # --- RIGHT CALLOUT CARD: KNOB ARCHITECTURE & COMBOS ---
    draw.rounded_rectangle([1080, 140, 1460, 780], radius=20, fill=(18, 22, 32, 255), outline=(55, 70, 95, 255), width=2)
    draw.text((1100, 165), "DUAL KNOBS & CHORD COMBOS", fill=(246, 196, 66, 255))

    right_items = [
        ("(( MASTER ))", "Dedicated analog potentiometer.\nGoverns direct TRS headphone and line out\nlevels with zero digital latency."),
        ("(( PARA ))", "Multi-axis optical push-encoder.\nTurn: Modulate active parameter\nClick: Cycle ORBIT -> WARP -> FLUX -> GRAV\nHold 1.2s: Quick-save preset\nHold 3s: Open Buffer Deep-Slice Editor"),
        ("CHORD: [VOL- & VOL+]", "Simultaneous press enters the\nFull-Screen Chromatic Tuner (Ref 430-450Hz)\nwith pass-through volume."),
        ("CHORD: [< & >]", "Simultaneous press enters BANK MODE:\nJump between the 4 Celestial Banks\n(Horizon, Stutter, Arp, Relativity)."),
        ("CHORD: [HOME & VOL-]", "Opens Groove Station / Rhythm Metronome\nsynced to granular grain clock.")
    ]

    rcy = 205
    for title, desc in right_items:
        draw.text((1100, rcy), title, fill=(246, 196, 66, 255))
        rcy += 24
        for line in desc.split("\n"):
            draw.text((1100, rcy), "  " + line, fill=(190, 210, 235, 255))
            rcy += 20
        rcy += 14

    # Save finalized diagram
    im.save(output_path, "PNG")
    print(f"Generated authentic hardware diagram: {output_path}")

if __name__ == "__main__":
    process_screen_bmps()
    generate_authentic_mvave_hardware_diagram()
